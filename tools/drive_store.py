"""drive_store.py - large files live in the Panel Twin Google Drive folder; git holds a pointer per file.

Same scheme as Hot-Water-Set (harness/scripts/drive_store.py), cut down for this repo:
  * drive-store.json names the Drive folder and the rules: every file at or above `large_file_bytes`, and every
    file with a listed extension under a listed directory (`*` matches one folder name).
  * Each selected file gets a tracked pointer `<file>.drive` (JSON: path, bytes, sha256, md5, mtime, drive_folder).
    The file itself is gitignored by the managed block this tool writes into .gitignore, and is stored in the
    Drive folder at the same repo-relative path. The working tree keeps the real file beside its pointer.
  * Transport: rclone, using the machine's existing `cpme-drive` sign-in re-rooted at the folder id in
    drive-store.json (no extra remote to configure). Drive reports md5, so the Drive side is checked by size and
    md5 and the local side by sha256.
  * A pointer is never rewritten for a file that now hashes differently unless --allow-change is given, and push
    never overwrites a different file already in Drive.

Run from anywhere:  python -I tools/drive_store.py scan | pointers [--allow-change] | push [--dry-run] | pull | verify [--local-only]
Exit codes: 0 ok, 1 a check found a problem, 2 refused.
"""
from __future__ import annotations

import argparse
import datetime as dt
import fnmatch
import glob
import hashlib
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
CONFIG = REPO / "drive-store.json"
SUFFIX = ".drive"
BLOCK_BEGIN = "# >>> drive-store: generated by tools/drive_store.py from drive-store.json; edit the JSON, not this block >>>"
BLOCK_END = "# <<< drive-store <<<"
CHUNK = 4 * 1024 * 1024
RCLONE_GLOB = str(Path.home() / "AppData/Local/Microsoft/WinGet/Packages/Rclone.Rclone_*/rclone-*/rclone.exe")


def die(msg: str) -> None:
    print(f"REFUSED: {msg}", file=sys.stderr)
    sys.exit(2)


def mb(n: int) -> str:
    return f"{n / 1048576:,.1f} MB"


def load_config() -> dict:
    if not CONFIG.is_file():
        die(f"missing {CONFIG.name}")
    return json.loads(CONFIG.read_text(encoding="utf-8-sig"))


def under(rel: str, pattern: str) -> bool:
    """True if repo-relative path `rel` is the directory `pattern` or inside it (`*` = one folder name)."""
    rp, pp = rel.split("/"), pattern.split("/")
    return len(rp) >= len(pp) and all(fnmatch.fnmatchcase(a, b) for a, b in zip(rp, pp))


def excluded(rel_dir: str, cfg: dict) -> bool:
    return any(under(rel_dir, p) or rel_dir.split("/")[-1] == p for p in cfg["exclude"])


def rule_for(rel: str, size: int, cfg: dict) -> str | None:
    if rel.endswith(SUFFIX) or rel in (".gitignore", ".gitattributes"):
        return None
    ext = rel.rsplit(".", 1)[-1].lower() if "." in rel.rsplit("/", 1)[-1] else ""
    for d, exts in cfg["directories"].items():
        if under(rel, d) and ext in exts:
            return "dir"
    return "size" if size >= int(cfg["large_file_bytes"]) else None


def hashes_of(path: Path) -> tuple[str, str]:
    s, m = hashlib.sha256(), hashlib.md5()
    with open(path, "rb") as fh:
        for block in iter(lambda: fh.read(CHUNK), b""):
            s.update(block)
            m.update(block)
    return s.hexdigest(), m.hexdigest()


def iso_mtime(path: Path) -> str:
    return dt.datetime.fromtimestamp(path.stat().st_mtime).replace(microsecond=0).isoformat(sep=" ")


def walk(cfg: dict):
    for root, dirs, files in os.walk(REPO):
        rel_root = Path(root).relative_to(REPO).as_posix()
        rel_root = "" if rel_root == "." else rel_root
        dirs[:] = sorted(d for d in dirs if not excluded(f"{rel_root}/{d}".strip("/"), cfg))
        for f in sorted(files):
            yield f"{rel_root}/{f}".strip("/"), Path(root) / f


def selected_files(cfg: dict) -> list[tuple[str, int, str]]:
    out = []
    for rel, p in walk(cfg):
        size = p.stat().st_size
        rule = rule_for(rel, size, cfg)
        if rule:
            out.append((rel, size, rule))
    return out


def all_pointers(cfg: dict) -> list[dict]:
    out = []
    for rel, p in walk(cfg):
        if rel.endswith(SUFFIX):
            d = json.loads(p.read_text(encoding="utf-8-sig"))
            if d.get("path") + SUFFIX != rel:
                die(f"pointer {rel} names a different path: {d.get('path')}")
            out.append(d)
    return out


def local_state(d: dict) -> str:
    f = REPO / d["path"]
    if not f.is_file():
        return "MISSING"
    if f.stat().st_size != d["bytes"]:
        return "MISMATCH"
    return "ok" if hashes_of(f)[0] == d["sha256"] else "MISMATCH"


def gitignore_escape(rel: str) -> str:
    out = rel.replace("\\", "\\\\")
    for ch in "[]*?":
        out = out.replace(ch, "\\" + ch)
    if out.endswith(" "):
        out = out[:-1] + "\\ "
    return "/" + out


def write_gitignore_block(cfg: dict, size_paths: list[str]) -> bool:
    block = [BLOCK_BEGIN, "# Files in the Google Drive store (drive-store.json). Their *.drive pointers are tracked; the files are not."]
    for d, exts in cfg["directories"].items():
        for e in sorted(exts):
            block.append(f"/{d}/**/*.{e}")
            block.append(f"/{d}/**/*.{e.upper()}")
    if size_paths:
        block.append(f"# Files at or above {int(cfg['large_file_bytes']):,} bytes outside those directories:")
        block += [gitignore_escape(p) for p in size_paths]
    block.append(BLOCK_END)
    gi = REPO / ".gitignore"
    old = gi.read_text(encoding="utf-8-sig").splitlines() if gi.exists() else []
    if BLOCK_BEGIN in old and BLOCK_END in old:
        i, j = old.index(BLOCK_BEGIN), old.index(BLOCK_END)
        new = old[:i] + block + old[j + 1:]
    else:
        new = old + ([""] if old and old[-1].strip() else []) + block
    if new == old:
        return False
    gi.write_text("\n".join(new) + "\n", encoding="utf-8", newline="\n")
    return True


class Rclone:
    def __init__(self, cfg: dict):
        exe = shutil.which("rclone") or next(iter(sorted(glob.glob(RCLONE_GLOB), reverse=True)), None)
        if not exe:
            die("rclone is not installed (winget install --id Rclone.Rclone --scope user)")
        self.exe = exe
        self.remote = f"{cfg['rclone_base_remote']},root_folder_id={cfg['drive_folder_id']}:"
        if f"{cfg['rclone_base_remote']}:" not in self._run(["listremotes"]).split():
            die(f"rclone has no remote '{cfg['rclone_base_remote']}' (Bob creates it once with his Google sign-in)")
        self._listing = None

    def _run(self, args: list[str]) -> str:
        r = subprocess.run([self.exe, *args], capture_output=True, text=True, encoding="utf-8", errors="replace")
        if r.returncode != 0:
            die(f"rclone {' '.join(args[:2])} failed ({r.returncode}):\n{r.stderr.strip()[-2000:]}")
        return r.stdout

    def listing(self, refresh=False) -> dict:
        if self._listing is None or refresh:
            out = self._run(["lsjson", "-R", "--files-only", "--hash", "--hash-type", "md5", self.remote])
            self._listing = {e["Path"]: {"bytes": e.get("Size", -1), "md5": (e.get("Hashes") or {}).get("md5", "")}
                             for e in json.loads(out or "[]")}
        return self._listing

    def stat(self, rel):
        return self.listing().get(rel)

    def _list_file(self, rels, name) -> Path:
        d = REPO / ".git" / "drive-store"
        d.mkdir(exist_ok=True)
        p = d / name
        p.write_text("\n".join(rels) + "\n", encoding="utf-8", newline="\n")
        return p

    def push(self, rels):
        lst = self._list_file(rels, "push-list.txt")
        self._run(["copy", str(REPO), self.remote, "--files-from", str(lst), "--checksum", "--transfers", "4", "-q"])
        self.listing(refresh=True)

    def pull(self, rels):
        lst = self._list_file(rels, "pull-list.txt")
        self._run(["copy", self.remote, str(REPO), "--files-from", str(lst), "--checksum", "--transfers", "4", "-q"])


def matches(d: dict, st: dict | None) -> str:
    if st is None:
        return "MISSING"
    if st["bytes"] != d["bytes"]:
        return "MISMATCH"
    if st.get("md5") and d.get("md5"):
        return "ok" if st["md5"] == d["md5"] else "MISMATCH"
    return "size-only"


def cmd_scan(a):
    cfg = load_config()
    sel = selected_files(cfg)
    for rel, size, rule in sel:
        ptr = "yes" if (REPO / (rel + SUFFIX)).exists() else "none"
        print(f"{rule:<4} {mb(size):>12}  pointer:{ptr:<5} {rel}")
    print(f"\n{len(sel)} file(s), {mb(sum(s for _, s, _ in sel))} selected for the Drive store")


def cmd_pointers(a):
    cfg = load_config()
    sel = selected_files(cfg)
    written = unchanged = 0
    changed = []
    for rel, size, rule in sel:
        f, ptr = REPO / rel, REPO / (rel + SUFFIX)
        mtime = iso_mtime(f)
        if ptr.exists():
            old = json.loads(ptr.read_text(encoding="utf-8-sig"))
            if old["bytes"] == size and old.get("mtime") == mtime:
                unchanged += 1
                continue
            sha, md5 = hashes_of(f)
            if sha == old["sha256"]:
                unchanged += 1
                continue
            if not a.allow_change:
                changed.append(f"{rel}: pointer {old['sha256'][:12]} vs file {sha[:12]}")
                continue
        else:
            sha, md5 = hashes_of(f)
        ptr.write_text(json.dumps({"path": rel, "bytes": size, "sha256": sha, "md5": md5, "mtime": mtime,
                                   "drive_folder": cfg["drive_folder_url"],
                                   "note": "Pointer to a file in the Panel Twin Google Drive store (same path under that "
                                           "folder). Written by tools/drive_store.py; never edited by hand."},
                                  indent=2) + "\n", encoding="utf-8", newline="\n")
        written += 1
    size_paths = sorted(rel for rel, _, rule in sel if rule == "size")
    gi = write_gitignore_block(cfg, size_paths)
    print(f"pointers: {written} written, {unchanged} unchanged, {len(sel)} selected, {mb(sum(s for _, s, _ in sel))}; "
          f".gitignore block {'updated' if gi else 'unchanged'}")
    if changed:
        print(f"{len(changed)} file(s) differ from their pointer and were NOT rewritten (use --allow-change only for a "
              "file that was never handed off):")
        for c in changed:
            print("  " + c)
        sys.exit(1)


def cmd_push(a):
    cfg = load_config()
    store = Rclone(cfg)
    pointers = all_pointers(cfg)
    to_push, problems, skipped, missing = [], [], 0, 0
    for d in pointers:
        if not (REPO / d["path"]).is_file():
            missing += 1
            continue
        state = matches(d, store.stat(d["path"]))
        if state == "ok":
            skipped += 1
        elif state == "MISSING":
            if local_state(d) == "ok":
                to_push.append(d["path"])
            else:
                problems.append(f"{d['path']}: working file does not match its pointer; run pointers first")
        else:
            problems.append(f"{d['path']}: a different file is already in Drive ({state}); not overwritten")
    total = sum(d["bytes"] for d in pointers if d["path"] in set(to_push))
    if a.dry_run:
        print(f"push (dry run): {len(to_push)} file(s), {mb(total)} would be copied; {skipped} already there")
        for r in to_push:
            print("  " + r)
        sys.exit(1 if problems else 0)
    copied = 0
    if to_push:
        print(f"copying {len(to_push)} file(s), {mb(total)}, to Drive ...")
        store.push(to_push)
        for d in pointers:
            if d["path"] in to_push:
                s = matches(d, store.stat(d["path"]))
                copied += s == "ok"
                if s != "ok":
                    problems.append(f"{d['path']}: after copy Drive reads {s}")
    print(f"push: {copied} copied and verified, {skipped} already in Drive, {missing} not in the working tree, "
          f"{len(problems)} problem(s)")
    for p in problems:
        print("  " + p)
    sys.exit(1 if problems else 0)


def cmd_pull(a):
    cfg = load_config()
    store = Rclone(cfg)
    pointers = all_pointers(cfg)
    want = [d["path"] for d in pointers if not (REPO / d["path"]).is_file() and matches(d, store.stat(d["path"])) == "ok"]
    if want:
        store.pull(want)
    bad = [d["path"] for d in pointers if d["path"] in want and local_state(d) != "ok"]
    print(f"pull: {len(want) - len(bad)} copied and verified, {len(bad)} problem(s)")
    sys.exit(1 if bad else 0)


def cmd_verify(a):
    cfg = load_config()
    store = None if a.local_only else Rclone(cfg)
    problems = 0
    pointers = all_pointers(cfg)
    for d in pointers:
        states = [f"local:{local_state(d)}"] + ([f"drive:{matches(d, store.stat(d['path']))}"] if store else [])
        problems += sum(not s.endswith(":ok") for s in states)
        print(f"{' '.join(states):<30} {d['path']}")
    print(f"\nverify: {len(pointers)} pointer(s), {mb(sum(d['bytes'] for d in pointers))}, {problems} problem(s)")
    sys.exit(1 if problems else 0)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("scan")
    p = sub.add_parser("pointers")
    p.add_argument("--allow-change", action="store_true")
    p = sub.add_parser("push")
    p.add_argument("--dry-run", action="store_true")
    sub.add_parser("pull")
    p = sub.add_parser("verify")
    p.add_argument("--local-only", action="store_true")
    a = ap.parse_args()
    {"scan": cmd_scan, "pointers": cmd_pointers, "push": cmd_push, "pull": cmd_pull, "verify": cmd_verify}[a.cmd](a)


if __name__ == "__main__":
    main()
